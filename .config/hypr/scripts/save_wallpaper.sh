#!/usr/bin/env bash

# Persists the wallpaper currently shown on a monitor into hyprpaper.conf.
#
# Usage: save_wallpaper.sh <target>
#   1     = left monitor (HDMI-A-1) only
#   2     = middle monitor (DP-1) only
#   3     = right monitor (DP-2) only
#   all   = all three monitors
#
# With a single screen, the other monitors are left exactly as they were in
# the file. With "all", every monitor is written from what is on screen now.

set -euo pipefail

CONFIG="${HYPRPAPER_CONF:-$HOME/.config/hypr/hyprpaper.conf}"

BEGIN_MARKER="# --- BEGIN generated by save_wallpaper.sh ---"
END_MARKER="# --- END generated by save_wallpaper.sh ---"

# Screen number -> monitor name, ordered left to right.
MONITORS=("HDMI-A-1" "DP-1" "DP-2")

usage() {
  echo "Usage: $(basename "$0") <1|2|3|all>   (1 = left, 2 = middle, 3 = right, all = every screen)" >&2
  exit 1
}

die() {
  hyprctl notify 3 4000 0 "Wallpaper not saved: $1"
  echo "Error: $1" >&2
  exit 1
}

trim() {
  local s="$1"
  s="${s#"${s%%[![:space:]]*}"}"
  printf '%s' "${s%"${s##*[![:space:]]}"}"
}

[[ $# -eq 1 && ( $1 =~ ^[123]$ || $1 == "all" ) ]] || usage
[[ -f "$CONFIG" ]] || die "hyprpaper.conf not found at $CONFIG"

# Empty target means "every monitor".
target=""
if [[ $1 =~ ^[123]$ ]]; then
  target="${MONITORS[$(($1 - 1))]}"
fi

# Snapshot what hyprpaper is showing right now, per monitor.
if ! active=$(hyprctl hyprpaper listactive 2>/dev/null) || [[ -z "$active" ]]; then
  die "hyprpaper is not running"
fi

live_wallpaper() {
  awk -v m="$1" -F' = ' '$1 == m { print $2; exit }' <<<"$active"
}

# Variables defined in the config, so "$vertical" can be resolved to a path.
declare -A vars=()
while IFS= read -r line; do
  if [[ "$line" =~ ^\$([A-Za-z_][A-Za-z0-9_]*)[[:space:]]*=[[:space:]]*(.*)$ ]]; then
    vars["\$${BASH_REMATCH[1]}"]="${BASH_REMATCH[2]}"
  fi
done < <(grep -E '^[[:space:]]*\$[A-Za-z_]' "$CONFIG" || true)

# Turn a value from the config into an absolute path, following $variables.
resolve() {
  local val="$1" depth=0
  while [[ "$val" == \$* && $depth -lt 10 ]]; do
    val="${vars[${val}]-}"
    ((depth++))
  done
  [[ "$val" == "~/"* ]] && val="$HOME/${val:2}"
  printf '%s' "$val"
}

# Wallpaper currently assigned to each monitor in the config file.
declare -A assigned=()
while IFS= read -r line; do
  body="${line#*=}"
  assigned["$(trim "${body%%,*}")"]="$(trim "${body#*,}")"
done < <(grep -E '^[[:space:]]*wallpaper[[:space:]]*=' "$CONFIG" || true)

# Screens being saved are rewritten. The rest keep whatever the file said
# (including their original $variable form); if a screen is missing from the
# file entirely, fall back to whatever it is showing now.
values=()
for monitor in "${MONITORS[@]}"; do
  if [[ -z "$target" || "$monitor" == "$target" ]]; then
    path="$(live_wallpaper "$monitor")"
    [[ -n "$path" ]] || die "could not read the current wallpaper for $monitor"
    values+=("$path")
  elif [[ -n "${assigned[$monitor]:-}" ]]; then
    values+=("${assigned[$monitor]}")
  else
    path="$(live_wallpaper "$monitor")"
    [[ -n "$path" ]] || die "no wallpaper recorded for $monitor"
    values+=("$path")
  fi
done

# Preload each distinct wallpaper once, then pin each monitor to its own.
block="$BEGIN_MARKER"$'\n'
for value in "${values[@]}"; do
  path="$(resolve "$value")"
  grep -qxF "preload = $path" <<<"$block" || block+="preload = $path"$'\n'
done
block+=$'\n'
for i in "${!MONITORS[@]}"; do
  block+="wallpaper = ${MONITORS[$i]}, ${values[$i]}"$'\n'
done
block+="$END_MARKER"

tmp=$(mktemp)
if grep -qxF "$BEGIN_MARKER" "$CONFIG"; then
  awk -v begin="$BEGIN_MARKER" -v end="$END_MARKER" -v block="$block" '
    $0 == begin { skip = 1; print block; next }
    $0 == end   { skip = 0; next }
    !skip      { print }
  ' "$CONFIG" >"$tmp"
else
  # First run: the block supersedes whatever was already active in the file.
  # Drop those lines so hyprpaper doesn't apply each wallpaper twice.
  # Comments and $variable definitions are kept.
  grep -vE '^[[:space:]]*(preload|wallpaper)[[:space:]]*=' "$CONFIG" | cat -s >"$tmp"
  printf '\n%s\n' "$block" >>"$tmp"
fi
mv "$tmp" "$CONFIG"

if [[ "$1" == "all" ]]; then
  hyprctl notify 5 3000 0 "All screens saved to hyprpaper.conf"
else
  idx=$(($1 - 1))
  hyprctl notify 5 3000 0 "Screen $1 set to: $(basename "$(resolve "${values[$idx]}")")"
fi
